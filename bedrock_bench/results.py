def machine_record(
    machine: Machine, fingerprint: Mapping[str, Any], facts: Mapping[str, Any], tsc_hz: float | None
) -> dict[str, Any]:
    """The ``machine`` block: hardware fingerprint, host facts, profile label and hash, and the profile's gates.

    The gates are recorded so that ``bbench analyze`` judges foreign load against the limits the run was made with.
    """
    merged = {**fingerprint, **facts}
    merged.update(
        {
            "label": machine.label or None,
            "tsc_hz_calibrated": round(tsc_hz) if tsc_hz else None,
            "profile_sha256": machine.profile_sha256,
            "gates": to_json(machine.gates),
        }
    )
    return {key: merged[key] for key in _MACHINE_KEYS if key in merged}


