def _dialect_for(server: str | None) -> Any:
    """The registered adapter's console dialect, or None when the server's adapter is not installed here."""
    if not server:
        return None
    from bedrock_bench import adapters

    try:
        return adapters.get(server).dialect
    except ConfigError:
        return None


def load_run(path: Path | str) -> RunData:
    """Load a run directory's raw files as :class:`~bedrock_bench.model.RunData` for :func:`metrics.compute`.

    Missing raw files load as empty series: a server that died at boot leaves no bot events. Log lines are split with
    the server's dialect when its adapter is installed; otherwise level and logger are unknown.
    """
    from bedrock_bench import console
    from bedrock_bench.sampling import series

    run_dir = RunDir.open(Path(path))
    record = run_dir.read_record()
    schema = record.get("schema")
    if schema != RUN_SCHEMA:
        raise ValueError(f"{run_dir.path}: unsupported run schema {schema!r} (this harness reads {RUN_SCHEMA})")

    def present(rel: str) -> Path | None:
        candidate = run_dir.file(rel)
        return candidate if candidate.is_file() else None

    def series_file(name: str) -> Path | None:
        return present(f"{SERIES_DIR}/{name}")

    dialect = _dialect_for((record.get("arm") or {}).get("server"))
    probe = series_file(series.PROBE_FILE)
    threads = series_file(series.THREADS_FILE)
    tick = series_file(series.TICK_FILE)
    process = series_file(series.PROCESS_FILE)
    machine = series_file(series.MACHINE_FILE)
    server_log = present(LOG_FILE)
    journal = present(JOURNAL_FILE)
    bots = present(BOTS_FILE)
    return RunData(
        run=record,
        probe=series.read_probe(probe) if probe else [],
        threads=series.read_threads(threads) if threads else ThreadSeries(),
        tick=series.read_tick(tick) if tick else [],
        process=series.read_process(process) if process else [],
        machine=series.read_machine(machine) if machine else [],
        bots=series.read_jsonl(bots) if bots else [],
        log=console.read_log(server_log, dialect) if server_log else [],
        commands=console.read_journal(journal) if journal else [],
    )


