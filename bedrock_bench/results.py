#: A session id: ``make_session_id`` output, or anything else that is safe as one directory name.
SESSION_RE = re.compile(r"^[0-9A-Za-z][0-9A-Za-z._-]*$")


def make_session_id(epoch_ms: int | None = None) -> str:
    """``<UTCyyyymmddThhmmssZ>-<4hex>``, shared by every run of one ``bbench run``."""
    if epoch_ms is None:
        epoch_ms = time.time_ns() // 1_000_000
    return f"{utc_compact(epoch_ms)}-{secrets.token_hex(2)}"


def make_run_id(arm_id: str, repeat: int, epoch_ms: int, suffix: str | None = None) -> str:
    """``<UTCyyyymmddThhmmssZ>-<arm>-r<k>-<4hex>``."""
    suffix = suffix if suffix is not None else secrets.token_hex(2)
    return f"{utc_compact(epoch_ms)}-{arm_id}-r{repeat}-{suffix}"


class RunDir:
    """One run's results directory. Use :meth:`create` for a new run and :meth:`open` for an existing one."""

    def __init__(self, path: Path) -> None:
        self.path = Path(path)
        self.run_id = self.path.name

    @classmethod
    def create(cls, session_dir: Path, arm_id: str, repeat: int) -> RunDir:
        """A new, empty directory with a unique run id. An existing directory is never reused."""
        for _ in range(64):
            epoch_ms = time.time_ns() // 1_000_000
            path = Path(session_dir) / make_run_id(arm_id, repeat, epoch_ms)
            try:
                path.mkdir(parents=True, exist_ok=False)
            except FileExistsError:
                continue
            (path / SERIES_DIR).mkdir()
            return cls(path)
        raise RuntimeError(f"cannot find an unused run id under {session_dir}")

    @classmethod
    def open(cls, path: Path) -> RunDir:
        path = Path(path)
        if not (path / RUN_FILE).is_file() and not (path / PARTIAL_FILE).is_file():
            raise FileNotFoundError(f"{path} is not a run directory (no {RUN_FILE} or {PARTIAL_FILE})")
        return cls(path)

    def __repr__(self) -> str:
        return f"RunDir({self.run_id!r})"

    # ---- paths ------------------------------------------------------------------------------------------------------

    def file(self, relative: str) -> Path:
        return self.path / relative

    def series(self, name: str) -> Path:
        return self.path / SERIES_DIR / name

    # ---- records ----------------------------------------------------------------------------------------------------

    def write_partial(self, record: Mapping[str, Any]) -> None:
        _write_json(self.path / PARTIAL_FILE, record)

    def write_run(self, record: Mapping[str, Any]) -> None:
        _write_json(self.path / RUN_FILE, record)

    def remove_partial(self) -> None:
        _retry(lambda: (self.path / PARTIAL_FILE).unlink(missing_ok=True))

    def read_record(self) -> dict[str, Any]:
        """run.json, or run.partial.json when the run never finished."""
        for name in (RUN_FILE, PARTIAL_FILE):
            path = self.path / name
            if path.is_file():
                return json.loads(path.read_text(encoding="utf-8"))
        raise FileNotFoundError(f"{self.path} has no {RUN_FILE}")

    # ---- raw files --------------------------------------------------------------------------------------------------

    def raw_files(self) -> list[str]:
        """Every raw file of the run as a POSIX path relative to the run directory, sorted."""
        found = []
        for path in self.path.rglob("*"):
            if not path.is_file() or path.name.endswith(_TMP_SUFFIX):
                continue
            rel = path.relative_to(self.path).as_posix()
            if rel not in RECORD_FILES:
                found.append(rel)
        return sorted(found)

    def file_hashes(self) -> dict[str, dict[str, Any]]:
        """``{relative path: {"sha256", "bytes"}}`` of every raw file (the ``files`` block of run.json)."""
        out = {}
        for rel in self.raw_files():
            data = (self.path / rel).read_bytes()
            out[rel] = {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
        return out


def _retry(action: Any, attempts: int = 50, delay_s: float = 0.02) -> Any:
    """Run ``action`` again while Windows reports the file as in use by a concurrent reader."""
    for attempt in range(attempts):
        try:
            return action()
        except PermissionError:
            if attempt == attempts - 1:
                raise
            time.sleep(delay_s)
    return None


def _write_json(path: Path, record: Mapping[str, Any]) -> None:
    """Write JSON atomically: a reader sees the old file or the new one, never a torn one."""
    text = json.dumps(record, indent=2, ensure_ascii=False, allow_nan=False) + "\n"
    tmp = path.with_name(path.name + _TMP_SUFFIX)
    tmp.write_text(text, encoding="utf-8", newline="\n")
    _retry(lambda: os.replace(tmp, path))


class JsonLines:
    """A gzip JSON-lines file written from several threads, flushed at least every ``flush_s`` seconds."""

    def __init__(self, path: Path, flush_s: float = 1.0) -> None:
        self.path = Path(path)
        self._fh: IO[str] | None = gzip.open(self.path, "wt", encoding="utf-8", newline="\n")
        self._lock = threading.Lock()
        self._flush_s = flush_s
        self._last_flush = time.monotonic()
        self.lines = 0

    def write(self, obj: Mapping[str, Any]) -> None:
        text = json.dumps(obj, ensure_ascii=False, separators=(",", ":")) + "\n"
        with self._lock:
            if self._fh is None:
                return
            self._fh.write(text)
            self.lines += 1
            now = time.monotonic()
            if now - self._last_flush >= self._flush_s:
                self._fh.flush()
                self._last_flush = now

    def close(self) -> None:
        with self._lock:
            if self._fh is not None:
                self._fh.close()
                self._fh = None


