def arm_record(arm: Any) -> dict[str, Any]:
    """The ``arm`` block. A local artifact is recorded by file name only."""
    return {
        "id": arm.id,
        "server": arm.server,
        "version": arm.version,
        "bds": arm.bds,
        "python": arm.python,
        "artifact": arm.artifact.name if arm.artifact is not None else None,
    }


def placement_record(placement: Placement) -> dict[str, Any]:
    return {
        "server_cpus": list(placement.server_cpus),
        "bot_cpus": list(placement.bot_cpus),
        "harness_cpus": list(placement.harness_cpus),
        "priority": placement.priority,
        "kind": placement.kind,
        "method": None,
        "verified": None,
    }


