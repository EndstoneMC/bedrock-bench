"""Run directories: layout, ``run.json`` assembly, the raw-file loader and schema validation.

A run directory is ``<out>/<session>/<run_id>/``. It is created once, with a unique id, and never overwritten or
deleted. While the run is in progress ``run.partial.json`` is rewritten after every phase, so a crashed harness
still leaves a record; at the end ``run.json`` replaces it and ``metrics.json`` is computed from the raw files, the
same way ``bbench analyze`` recomputes it later.

=========================  ==========================================================================================
File                       Content
=========================  ==========================================================================================
``run.json``               provenance, configuration, config keys set, marks, interventions, spread, outcome
``metrics.json``           computed from the raw files; regenerated by ``bbench analyze``
``server.log.gz``          ``<mono_ns>\\t<epoch_ms>\\t<line>`` for every console line
``commands.jsonl.gz``      every console write with its enqueue and send times, lane and origin
``bots.jsonl.gz``          the bot's JSONL events, each with the harness receive time ``rx_ns``
``bots.stderr.log``        the bot's standard error, kept only when it is not empty
``series/*``               sampler output (see :mod:`bedrock_bench.sampling.series`)
``config/written/``        rendered server configs as written before launch
``config/after/``          the same files as found after shutdown
``crash/``                 log tail and crash files, when the server died or exited nonzero
=========================  ==========================================================================================

``run.json`` never holds a host name, user name or absolute path: :func:`finalize` scrubs it with
:class:`bedrock_bench.provenance.Scrubber` and treats anything left as a harness fault.
"""

