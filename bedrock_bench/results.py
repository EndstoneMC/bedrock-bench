def apply_layout(record: dict[str, Any], layout: Layout) -> None:
    """Record what ``prepare`` produced: each rendered config with its keys before and after, world and exe hash."""
    record["config_files"] = [{**to_json(c), "after_sha256": None} for c in layout.config_files]
    record["world"] = {"fresh": layout.world.fresh, "generator": layout.world.generator}
    exe_sha256 = layout.extra.get("exe_sha256")
    record["install"]["exe_sha256_before"] = exe_sha256 if isinstance(exe_sha256, str) else None


def interference_record(
    run_dir: RunDir, origin: Origin, windows: Mapping[str, tuple[float, float]], top_n: int = 5
) -> dict[str, dict[str, Any]]:
    """Per-window interference summary for run.json: foreign load, its 10 s peak, foreign load on the server's CPUs,
    the harness's own CPU and the busiest foreign processes.

    Metrics recompute the foreign-load figures from ``series/machine.csv.gz``; the harness CPU and the process names
    exist only here.
    """
    from bedrock_bench.metrics import cpu
    from bedrock_bench.sampling import series

    machine_path = run_dir.series(series.MACHINE_FILE)
    if not machine_path.is_file():
        return {}
    samples = [
        MachineSample(s.t_ns - origin.mono_ns, s.per_cpu_busy, s.foreign_cores, s.foreign_server_set_cores)
        for s in series.read_machine(machine_path)
    ]
    groups = [((t - origin.mono_ns) / NS_PER_S, cores) for t, cores in series.read_group_cores(machine_path)]
    top_path = run_dir.series(series.FOREIGN_TOP_FILE)
    tops = series.read_jsonl(top_path) if top_path.is_file() else []
    out: dict[str, dict[str, Any]] = {}
    for name, (t0, t1) in windows.items():
        foreign = cpu.foreign(samples, t0, t1)
        harness = [cores["harness"] for t, cores in groups if t0 <= t <= t1]
        out[name] = {
            "foreign_cores": _floor(foreign.cores if foreign else None),
            "peak_10s": _floor(foreign.peak_10s if foreign else None),
            "server_set": _floor(foreign.server_set_cores if foreign else None),
            "harness_cores": _floor(sum(harness) / len(harness) if harness else None),
            "top": _top_foreign(tops, origin, t0, t1, top_n),
        }
    return out


def _floor(value: float | None) -> float | None:
    return None if value is None else round(max(0.0, value), 4)


def _top_foreign(
    tops: Sequence[Mapping[str, Any]], origin: Origin, t0: float, t1: float, n: int
) -> list[dict[str, Any]]:
    """The busiest foreign processes over a window, by mean cores across the 10 s scans inside it."""
    scans = [entry for entry in tops if t0 <= (int(entry.get("t_ns", 0)) - origin.mono_ns) / NS_PER_S <= t1]
    if not scans:
        return []
    totals: dict[str, float] = {}
    for scan in scans:
        for row in scan.get("top") or ():
            name = str(row.get("name") or "?")
            totals[name] = totals.get(name, 0.0) + float(row.get("cores") or 0.0)
    ranked = sorted(totals.items(), key=lambda item: (-item[1], item[0]))[:n]
    return [{"name": name, "cores": round(total / len(scans), 3)} for name, total in ranked]


