@dataclass(frozen=True)
class Outcome:
    """The recorded result of a finished run."""

    run_dir: RunDir
    status: Status
    exit_code: ExitCode
    reasons: tuple[str, ...]
    flags: tuple[str, ...]


def finalize(
    run_dir: RunDir,
    record: dict[str, Any],
    *,
    reasons: Iterable[str],
    flags: Iterable[str],
    scrub_roots: Mapping[str, Path] | None = None,
) -> Outcome:
    """Write the final run.json and metrics.json.

    ``reasons`` are ``"<gate>: <detail>"`` facts only the live run could see (harness faults, config read-back);
    the status itself comes from :func:`bedrock_bench.metrics.compute` over the raw files on disk, so ``bbench analyze``
    reproduces it exactly.
    """
    from bedrock_bench import metrics
    from bedrock_bench.provenance import Scrubber

    scrubber = Scrubber(dict(scrub_roots or {}))
    recorded = [scrubber.text(reason) for reason in dict.fromkeys(reasons)]
    record = scrubber(record)
    leaks = scrubber.leaks(record)
    if leaks:
        log.error("run.json still names a local path, user or host after scrubbing: %s", leaks[:3])
        recorded.append("harness_ok: run.json still names a local path, user or host after scrubbing")
    record.pop("partial", None)
    record["status_reasons"] = recorded
    record["flags"] = sorted(set(flags))
    record["files"] = run_dir.file_hashes()
    provisional = Status.INVALID if recorded else Status.OK
    record["status"] = provisional.value
    record["exit_code"] = int(provisional.exit_code)
    run_dir.write_run(record)

    try:
        doc = metrics.compute(load_run(run_dir.path))
    except Exception as exc:  # a formula bug must not lose the run; it is recorded as a harness fault
        log.exception("metrics computation failed")
        recorded.append(scrubber.text(f"harness_ok: metrics computation failed: {type(exc).__name__}: {exc}"))
        record["status_reasons"] = recorded
        record["status"] = Status.INVALID.value
        record["exit_code"] = int(ExitCode.INVALID)
        run_dir.write_run(record)
        run_dir.remove_partial()
        return Outcome(
            run_dir, Status.INVALID, ExitCode.INVALID, tuple(record["status_reasons"]), tuple(record["flags"])
        )
    metrics.write(run_dir.path / METRICS_FILE, doc)
    status = Status(doc["status"])
    record["status"] = status.value
    record["status_reasons"] = list(doc["status_reasons"])
    record["flags"] = list(doc["flags"])
    record["exit_code"] = int(status.exit_code)
    run_dir.write_run(record)
    run_dir.remove_partial()
    return Outcome(run_dir, status, status.exit_code, tuple(doc["status_reasons"]), tuple(doc["flags"]))


