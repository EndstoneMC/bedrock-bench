#: ``schema`` ids of the JSON documents the harness writes, and the schema file that validates each.
SCHEMA_FILES = {RUN_SCHEMA: "run", METRICS_SCHEMA: "metrics"}


class _Validators:
    def __init__(self, jsonschema: Any) -> None:
        self._jsonschema = jsonschema
        self._cache: dict[str, Any] = {}

    def get(self, name: str) -> Any:
        if name not in self._cache:
            schema = load_schema(name)
            cls = self._jsonschema.validators.validator_for(schema)
            self._cache[name] = cls(schema, format_checker=cls.FORMAT_CHECKER)
        return self._cache[name]

    def errors(self, name: str, instance: Any, where: str, limit: int = 20) -> list[str]:
        found = sorted(self.get(name).iter_errors(instance), key=lambda e: [str(p) for p in e.absolute_path])
        out = []
        for error in found[:limit]:
            pointer = "/".join(str(p) for p in error.absolute_path) or "(root)"
            out.append(f"{where}: {pointer}: {error.message}")
        if len(found) > limit:
            out.append(f"{where}: {len(found) - limit} more errors")
        return out


def _display(path: Path) -> str:
    try:
        return path.resolve().relative_to(Path.cwd().resolve()).as_posix()
    except (ValueError, OSError):
        return path.as_posix()


def _json_lines(path: Path) -> Iterator[tuple[int, Any]]:
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8") as fh:
        for number, line in enumerate(fh, 1):
            if line.strip():
                yield number, json.loads(line)


def _check_document(path: Path, validators: _Validators) -> tuple[list[str], int]:
    """Problems with one file and the number of documents checked in it."""
    where = _display(path)
    name = path.name
    try:
        if name.endswith((".jsonl", ".jsonl.gz")):
            problems, count = [], 0
            for number, event in _json_lines(path):
                problems += validators.errors("bot-event", event, f"{where}:{number}", limit=5)
                count += 1
            return problems, count
        document = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError, EOFError) as exc:
        return [f"{where}: cannot read: {exc}"], 0
    schema_id = document.get("schema") if isinstance(document, dict) else None
    schema = SCHEMA_FILES.get(str(schema_id))
    if schema is None:
        return [f"{where}: no schema for {schema_id!r}"], 0
    return validators.errors(schema, document, where), 1


def _check_run_dir(run_dir: Path, validators: _Validators) -> tuple[list[str], int]:
    """Schema problems of a run directory's documents, and raw files that do not match run.json ``files``."""
    problems: list[str] = []
    count = 0
    record_path = run_dir / RUN_FILE if (run_dir / RUN_FILE).is_file() else run_dir / PARTIAL_FILE
    for path in (record_path, run_dir / METRICS_FILE, run_dir / BOTS_FILE):
        if path.is_file():
            found, n = _check_document(path, validators)
            problems += found
            count += n
    if record_path.name == RUN_FILE:
        try:
            record = json.loads(record_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return problems, count
        listed = record.get("files") or {}
        on_disk = set(RunDir(run_dir).raw_files())
        where = _display(run_dir)
        for rel, entry in sorted(listed.items()):
            path = run_dir / rel
            if not path.is_file():
                problems.append(f"{where}: {rel} is listed in run.json but missing")
                continue
            data = path.read_bytes()
            if hashlib.sha256(data).hexdigest() != entry.get("sha256") or len(data) != entry.get("bytes"):
                problems.append(f"{where}: {rel} does not match its hash in run.json")
        for rel in sorted(on_disk - set(listed)):
            problems.append(f"{where}: {rel} is not listed in run.json files")
    return problems, count


def validate_paths(paths: Iterable[Path], validators: _Validators) -> tuple[list[str], int]:
    problems: list[str] = []
    count = 0
    for path in map(Path, paths):
        if path.is_dir():
            if (path / RUN_FILE).is_file() or (path / PARTIAL_FILE).is_file():
                run_dirs = [path]
            else:
                run_dirs = sorted({p.parent for name in (RUN_FILE, PARTIAL_FILE) for p in path.rglob(name)})
            if not run_dirs:
                problems.append(f"{_display(path)}: no run directories found")
            for run_dir in run_dirs:
                found, n = _check_run_dir(run_dir, validators)
                problems += found
                count += n
        elif path.is_file():
            found, n = _check_document(path, validators)
            problems += found
            count += n
        else:
            problems.append(f"{_display(path)}: no such file or directory")
    return problems, count


def validate_cli(args: argparse.Namespace) -> int:
    """``bbench validate PATH...``: check run directories and result files against the schemas.

    A run directory has its run.json (or run.partial.json), metrics.json and bot events checked, and every raw file
    compared with its hash in run.json. A directory without run.json is searched for run directories. Single files
    are recognised by their ``schema`` field (run, metrics) or by extension (``.jsonl``/``.jsonl.gz`` bot events).
    """
    try:
        import jsonschema
    except ImportError:
        print("bbench validate: needs the jsonschema package (pip install jsonschema)", file=sys.stderr)
        return ExitCode.USAGE
    problems, count = validate_paths(args.paths, _Validators(jsonschema))
    for problem in problems:
        print(problem)
    print(f"{count} documents checked, {len(problems)} problems", file=sys.stderr)
    if any(p.endswith(("no such file or directory", "no run directories found")) for p in problems):
        return ExitCode.USAGE
    return ExitCode.INVALID if problems else ExitCode.OK


